"""Build the "wrong site" acceptance example of docs/APS-IMPROVEMENT-PLAN.md as importable case files.

Two layouts of two 8 x 8 m mirrors: A north of the tower at (-20, 92), (20, 108), B south at (-20, -92),
(20, -108). 20 scenarios from the Aksai demo weather (sun_bins, seed 7): h_s = actual hours of the
cluster, d_s = its time-average DNI. Map of scenario s, given at the corners of the square site
[-125, 125]^2 (bilinear inside): D_s(x, y) = d_s [0.53 - (0.33 + 0.07 cos alpha_s) y / 125], alpha_s =
sun azimuth. Three candidate heights over 48 % of the receiver height, no azimuth offset, no defocus,
fixed receiver grid, 2-D flux of the whole receiver, lambda = 0.05.

    python scripts/make_wrong_site_example.py [--out cases/wrong_site]

Writes wrong_site.yaml (spatial maps), wrong_site_mean.yaml (the field-mean DNI of every map),
scenarios.csv, scenarios_mean.csv, dni_maps.csv, layout_A.csv and layout_B.csv. Expected scores
(MWh equivalent): maps A 41.449 / B 84.785 (B wins); field-mean DNI A 72.817 / B 59.142 (A wins).
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd
import yaml

from cspaps import load_case, sun

ROOT = Path(__file__).resolve().parents[1]
A = [(-20.0, 92.0, 5.0), (20.0, 108.0, 5.0)]
B = [(-20.0, -92.0, 5.0), (20.0, -108.0, 5.0)]
HALF = 125.0


def build(out: Path) -> dict:
    out.mkdir(parents=True, exist_ok=True)
    demo = load_case(ROOT / "cases" / "aksai_demo.yaml")
    demo.annual.representative_dni = "time_mean"
    bins = sun.sun_bins(sun.hourly_samples(demo), 20, seed=7, weighting="time_mean")
    ids = [f"S{k + 1:02d}" for k in range(len(bins))]
    table = pd.DataFrame({"scenario_id": ids, "elevation_deg": np.round(bins.elevation, 6),
                          "azimuth_deg": np.round(bins.azimuth, 6), "hours": np.round(bins.weight_h, 6),
                          "dni_w_m2": np.round(bins.dni, 6), "map_id": [f"{i}_gradient" for i in ids],
                          "actual_hours": np.round(bins.actual_hours, 6), "hourly_members": bins.members})
    rows = []
    for i, r in table.iterrows():
        slope = (0.33 + 0.07 * np.cos(np.radians(r["azimuth_deg"]))) / HALF
        for x in (-HALF, HALF):
            for y in (-HALF, HALF):
                rows.append({"map_id": r["map_id"], "x": x, "y": y, "value": r["dni_w_m2"] * (0.53 - slope * y)})
    maps = pd.DataFrame(rows)
    table.to_csv(out / "scenarios.csv", index=False)
    mean = table.copy()
    mean["dni_w_m2"] = np.round(0.53 * table["dni_w_m2"], 6)  # the field mean of each map (linear in y)
    mean["map_id"] = "uniform"
    mean.to_csv(out / "scenarios_mean.csv", index=False)
    maps.to_csv(out / "dni_maps.csv", index=False, float_format="%.17g")
    for name, xyz in (("A", A), ("B", B)):
        pd.DataFrame({"id": [1, 2], "x": [p[0] for p in xyz], "y": [p[1] for p in xyz], "z": [p[2] for p in xyz]}
                     ).to_csv(out / f"layout_{name}.csv", index=False)
    base = yaml.safe_load((ROOT / "cases" / "aksai_demo.yaml").read_text(encoding="utf-8"))
    rel = Path("..") / "aksai_2024_dni.csv"
    base["name"] = "wrong_site"
    base["weather"] = {"source": "file", "file": str(rel)}
    base["field"] = {"layout_file": "layout_A.csv", "exclusion_radius": 50,
                     "boundary": [[-HALF, -HALF], [HALF, -HALF], [HALF, HALF], [-HALF, HALF]]}
    base["aps"].update({"n_height_levels": 3, "height_span": 0.48, "azimuth_offsets_deg": [0.0],
                        "allow_defocus": False, "auto_grid": False})
    base["uniformity"].update({"enabled": True, "mode": "weighted", "weight": 0.05, "panels": None, "z_range": None})
    base["layout_opt"].update({"n_heliostats": 2, "uniformity_weight": 0.05, "aps_weight": None, "workers": 1})
    base["annual"]["representative_dni"] = "time_mean"
    base["scenarios"] = {"source": "file", "file": "scenarios.csv", "map_model": "file", "map_file": "dni_maps.csv",
                         "map_unit": "w_m2", "map_normalize": "none"}
    (out / "wrong_site.yaml").write_text(
        "# Acceptance example \"a site that picks the wrong layout\" (docs/APS-IMPROVEMENT-PLAN.md).\n"
        "# Generated by scripts/make_wrong_site_example.py. Spatial DNI maps: B (south) wins.\n"
        + yaml.safe_dump(base, allow_unicode=True, sort_keys=False), encoding="utf-8")
    base["name"] = "wrong_site_mean"
    base["scenarios"] = {"source": "file", "file": "scenarios_mean.csv", "map_model": "uniform"}
    (out / "wrong_site_mean.yaml").write_text(
        "# The same example with the field-mean DNI of every map (one value for the whole field): A (north) wins.\n"
        + yaml.safe_dump(base, allow_unicode=True, sort_keys=False), encoding="utf-8")
    return {"actual_hours": float(table["hours"].sum()), "n": len(table), "folder": str(out)}


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--out", default=str(ROOT / "cases" / "wrong_site"))
    print(build(Path(p.parse_args().out)))
